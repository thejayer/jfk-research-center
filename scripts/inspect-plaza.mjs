import { chromium } from 'playwright-core';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
const dir = 'docs/dealey-plaza-1963'; await fs.mkdir(dir,{recursive:true});
const browser = await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1500,height:1100},deviceScaleFactor:1});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3000/dealey-plaza/trajectory',{waitUntil:'networkidle'});
await page.locator('canvas').waitFor();
await page.locator('canvas').scrollIntoViewIfNeeded();
// Label visibility must preserve a manually adjusted camera.
await page.getByLabel('Labels',{exact:true}).uncheck();
await page.getByRole('button',{name:'Zoom in',exact:true}).click();
const zoomedWithoutLabels=await page.locator('canvas').screenshot();
await page.getByLabel('Labels',{exact:true}).check();
await page.getByLabel('Labels',{exact:true}).uncheck();
const labelsPreserveCamera=zoomedWithoutLabels.equals(await page.locator('canvas').screenshot());
assert(labelsPreserveCamera,'Toggling labels preserves the manually adjusted camera');
await page.getByLabel('Labels',{exact:true}).check();
await page.getByRole('button',{name:'Reset view',exact:true}).click();
const baseline=await page.locator('canvas').screenshot();
const bounds=await page.locator('canvas').boundingBox();
await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+bounds.height*.5);
await page.mouse.down();await page.mouse.move(bounds.x+bounds.width*.65,bounds.y+bounds.height*.55,{steps:8});await page.mouse.up();
assert(!baseline.equals(await page.locator('canvas').screenshot()),'Orbit drag changes rendered view');
await page.getByRole('button',{name:'Reset view',exact:true}).click();
await page.screenshot({path:`${dir}/overview.png`});
for(const name of ['overhead','depository','elm','knoll','window']){
 await page.getByLabel('Reconstruction viewpoint').selectOption(name);
 await page.screenshot({path:`${dir}/${name}.png`});
}
await page.getByRole('button',{name:'Reset view',exact:true}).click();
await page.getByLabel('Legacy ray', {exact:true}).check();
await page.getByRole('button',{name:'Zoom in',exact:true}).click();
await page.getByRole('button',{name:'Zoom out',exact:true}).click();
await page.getByRole('button',{name:'Z313',exact:false}).click();
assert.equal(await page.getByRole('button',{name:'Z313',exact:false}).getAttribute('aria-pressed'),'true');
await page.getByLabel('Origin east/west').fill('-40');
await page.screenshot({path:`${dir}/ray-controls.png`});
await page.getByLabel('Low power',{exact:true}).check();
await page.getByLabel('Labels',{exact:true}).uncheck();
await page.screenshot({path:`${dir}/low-power.png`});
await page.setViewportSize({width:390,height:844});
await page.locator('canvas').scrollIntoViewIfNeeded();
await page.screenshot({path:`${dir}/mobile.png`});
const horizontalOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
assert.equal(horizontalOverflow,false);
const a11y=await new AxeBuilder({page}).include('[aria-label="Dealey Plaza 3D trajectory scene"]').analyze();
const fallback=await context.newPage();
await fallback.addInitScript(()=>{
 const getContext=HTMLCanvasElement.prototype.getContext;
 HTMLCanvasElement.prototype.getContext=function(type,...args){return /webgl/i.test(type)?null:getContext.call(this,type,...args);};
});
await fallback.goto('http://localhost:3000/dealey-plaza/trajectory',{waitUntil:'networkidle'});
await fallback.getByRole('status').filter({hasText:'3D rendering is unavailable'}).waitFor();
assert.equal(await fallback.getByLabel('Origin east/west').isEnabled(),true);
await fallback.screenshot({path:`${dir}/webgl-fallback.png`});
await fs.writeFile(`${dir}/browser-results.json`,JSON.stringify({errors,canvasCount:await page.locator('canvas').count(),horizontalOverflow,orbitDrag:true,frameSelection:true,labelsPreserveCamera,webglFallback:true,a11yViolations:a11y.violations.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>n.target)}))},null,2));
assert.equal(errors.length,0);
await browser.close();
